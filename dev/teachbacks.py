def block(q, keys):
    return ":::teachback\n" + q + "\n" + "\n".join(">> " + k for k in keys) + "\n:::\n"

missing = []
for fn in sorted(os.listdir(os.path.join(ROOT, "content", "lessons"))):
    lid = fn[:-3]
    p = os.path.join(ROOT, "content", "lessons", fn)
    s = open(p).read()
    if ":::teachback" in s:
        continue
    if lid not in TB:
        missing.append(lid)
        continue
    q, keys = TB[lid]
    b = block(q, keys)
    m = re.search(r"^:::quiz", s, re.M)
    if m:
        s = s[:m.start()] + b + "\n" + s[m.start():]
    else:
        s = s.rstrip("\n") + "\n\n" + b
    open(p, "w").write(s)
print("missing:", missing)
